/*
 * kwx_ts — QuickJS runtime host implementation (Phase 1/4).
 *
 * Creates a runtime with an 8 MiB stack, a context, the `__kwx_native` global
 * object carrying `__kwx_print` plus the generated kwxFFI thunks and the
 * hand-written Deno helpers, and evaluates the embedded `runtime/deno_shim.js`
 * (which installs `console`, `TextEncoder`, and `Deno`) before loading the
 * entry module through the JS global `__kwx_run_main`.
 */

#include "quickjs_host.h"

#include <chrono>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <string>
#include <tuple>
#include <vector>

#include "runtime_bindings.h"

/* Embedded runtime/deno_shim.js, produced by kwx_ts_embed_file(). These have
 * external linkage and are defined in the generated embedding translation unit,
 * so they must stay outside the anonymous namespace. */
extern const char kwx_deno_shim[];
extern const unsigned int kwx_deno_shim_len;

/* QuickJS bytecode for third_party/sucrase.bundle.js, generated at build time
 * by qjsc (see CMakeLists.txt). Evaluated once, after the Deno shim, so the
 * loader can transpile TypeScript. */
extern const std::uint8_t kwx_sucrase_bytecode[];
extern const std::uint32_t kwx_sucrase_bytecode_size;

namespace {
constexpr std::int64_t KWX_MAX_STACK_SIZE = 8LL * 1024LL * 1024LL;

JSRuntime *kwx_g_runtime = nullptr;
JSContext *kwx_g_context = nullptr;
std::vector<std::string> kwx_g_args;
int kwx_g_exit_code = 0;
bool kwx_g_exit_requested = false;

void KwxTraceMark(const char *label);

/* __kwx_trace(label) — emit a startup timing mark; a no-op unless tracing is
 * enabled. Frees every value it creates. */
JSValue kwx_js_trace(JSContext *ctx, JSValueConst /*this_val*/, int argc,
                     JSValueConst *argv) {
  if (argc < 1) {
    return JS_UNDEFINED;
  }

  const char *label = JS_ToCString(ctx, argv[0]);
  if (label == nullptr) {
    return JS_EXCEPTION;
  }

  KwxTraceMark(label);
  JS_FreeCString(ctx, label);
  return JS_UNDEFINED;
}

/* __kwx_print(stream, text) — stdout when stream is 0, stderr otherwise. */
JSValue kwx_js_print(JSContext *ctx, JSValueConst /*this_val*/, int argc,
                     JSValueConst *argv) {
  std::int32_t stream = 0;
  if (argc > 0) {
    std::ignore = JS_ToInt32(ctx, &stream, argv[0]);
  }

  const char *text = nullptr;
  if (argc > 1) {
    text = JS_ToCString(ctx, argv[1]);
  }

  const char *actual_text = (text != nullptr) ? text : "";
  std::FILE *target_stream = (stream == 0) ? stdout : stderr;
  std::fputs(actual_text, target_stream);
  std::fputc('\n', target_stream);
  std::fflush(target_stream);

  if (text != nullptr) {
    JS_FreeCString(ctx, text);
  }

  return JS_UNDEFINED;
}

/* Print the pending exception text plus its `stack` property to stderr. */
void kwx_report_exception(JSContext *ctx) {
  JSValue exception = JS_GetException(ctx);

  const char *message = JS_ToCString(ctx, exception);
  if (message != nullptr) {
    std::fprintf(stderr, "[kwx_ts] Uncaught %s\n", message);
    JS_FreeCString(ctx, message);
  }

  if (JS_IsObject(exception)) {
    JSValue stack = JS_GetPropertyStr(ctx, exception, "stack");
    if (!JS_IsUndefined(stack) && !JS_IsNull(stack)) {
      const char *stack_text = JS_ToCString(ctx, stack);
      if (stack_text != nullptr) {
        std::fprintf(stderr, "%s\n", stack_text);
        JS_FreeCString(ctx, stack_text);
      }
    }
    JS_FreeValue(ctx, stack);
  }

  JS_FreeValue(ctx, exception);
}

/* Evaluate a global-scope script; report and return false on failure. */
bool kwx_evaluate_global(const char *source, std::size_t length,
                         const char *name) {
  JSValue result =
      JS_Eval(kwx_g_context, source, length, name, JS_EVAL_TYPE_GLOBAL);
  const bool script_ok = !JS_IsException(result);
  JS_FreeValue(kwx_g_context, result);
  if (!script_ok) {
    kwx_report_exception(kwx_g_context);
  }
  return script_ok;
}

/* Evaluate precompiled QuickJS bytecode. JS_ReadObject validates the bytecode
 * version and checksum, so bytecode generated by a different QuickJS build
 * fails loudly instead of misbehaving. */
bool kwx_evaluate_bytecode(const std::uint8_t *bytecode,
                           std::uint32_t bytecode_size, const char *name) {
  JSValue compiled = JS_ReadObject(kwx_g_context, bytecode,
                                   static_cast<std::size_t>(bytecode_size),
                                   JS_READ_OBJ_BYTECODE);
  if (JS_IsException(compiled)) {
    kwx_report_exception(kwx_g_context);
    return false;
  }

  // JS_EvalFunction takes ownership of the compiled function object.
  JSValue result = JS_EvalFunction(kwx_g_context, compiled);
  const bool script_ok = !JS_IsException(result);
  JS_FreeValue(kwx_g_context, result);
  if (!script_ok) {
    std::fprintf(stderr, "[kwx_ts] Failed to evaluate bytecode '%s'\n", name);
    kwx_report_exception(kwx_g_context);
  }
  return script_ok;
}

/* True when KWX_TS_TRACE is set to a non-empty value. Resolved once; the
 * disabled path must stay clock- and allocation-free. */
bool kwx_trace_enabled() {
  static const bool trace_enabled = [] {
    const char *trace_value = std::getenv("KWX_TS_TRACE");
    return trace_value != nullptr && trace_value[0] != '\0';
  }();
  return trace_enabled;
}

/* Emit one `[kwx-trace] <ms> ms  <label>` line to stderr when tracing is on.
 * The first call establishes the time origin (process/runtime init start). */
void KwxTraceMark(const char *label) {
  if (!kwx_trace_enabled()) {
    return;
  }

  static const std::chrono::steady_clock::time_point trace_start =
      std::chrono::steady_clock::now();
  const std::chrono::steady_clock::time_point trace_now =
      std::chrono::steady_clock::now();
  const double elapsed_ms =
      std::chrono::duration<double, std::milli>(trace_now - trace_start)
          .count();
  std::fprintf(stderr, "[kwx-trace] %9.2f ms  %s\n", elapsed_ms, label);
  std::fflush(stderr);
}

} // namespace

void kwx_trace_mark(const char *label) { KwxTraceMark(label); }

bool kwx_runtime_init() {
  if (kwx_g_context != nullptr) {
    return true;
  }

  kwx_g_runtime = JS_NewRuntime();
  if (kwx_g_runtime == nullptr) {
    std::fprintf(stderr, "[kwx_ts] Failed to create QuickJS runtime\n");
    return false;
  }

  KwxTraceMark("runtime-created");

  JS_SetMaxStackSize(kwx_g_runtime, KWX_MAX_STACK_SIZE);

  kwx_g_context = JS_NewContext(kwx_g_runtime);
  if (kwx_g_context == nullptr) {
    std::fprintf(stderr, "[kwx_ts] Failed to create QuickJS context\n");
    JS_FreeRuntime(kwx_g_runtime);
    kwx_g_runtime = nullptr;
    return false;
  }

  KwxTraceMark("context-created");

  JSValue global_object = JS_GetGlobalObject(kwx_g_context);

  JSValue native_object = JS_NewObject(kwx_g_context);
  JSValue print_function =
      JS_NewCFunction(kwx_g_context, kwx_js_print, "__kwx_print", 2);
  JS_SetPropertyStr(kwx_g_context, native_object, "__kwx_print",
                    print_function);

  JSValue trace_function =
      JS_NewCFunction(kwx_g_context, kwx_js_trace, "__kwx_trace", 1);
  JS_SetPropertyStr(kwx_g_context, native_object, "__kwx_trace",
                    trace_function);

  KwxTraceMark("native-object-created");

  // Let the active phase mount its native bindings on the same object before it
  // is handed to the global scope (Phase 2: spike bindings).
  kwx_host_register_bindings(kwx_g_context, native_object);

  KwxTraceMark("bindings-registered");

  JS_SetPropertyStr(kwx_g_context, global_object, "__kwx_native",
                    native_object);

  JS_FreeValue(kwx_g_context, global_object);

  // Deno shim (runtime/deno_shim.js) is embedded in the executable and
  // evaluated once, after the native object is published and before any user
  // module loads.
  const bool deno_shim_ok = kwx_evaluate_global(
      kwx_deno_shim, static_cast<std::size_t>(kwx_deno_shim_len),
      "<kwx_deno_shim>");
  KwxTraceMark("deno-shim-evaluated");
  if (!deno_shim_ok) {
    kwx_runtime_shutdown();
    return false;
  }

  // Sucrase (third_party/sucrase.bundle.js) is precompiled to bytecode and
  // evaluated once, after the Deno shim so __kwx_transpile() can use it, and
  // before any module is loaded. It publishes the global `__kwx_sucrase`.
  const bool sucrase_ok = kwx_evaluate_bytecode(
      kwx_sucrase_bytecode, kwx_sucrase_bytecode_size, "<kwx_sucrase_bundle>");
  KwxTraceMark("sucrase-bundle-evaluated");
  if (!sucrase_ok) {
    kwx_runtime_shutdown();
    return false;
  }

  return true;
}

void kwx_runtime_shutdown() {
  if (kwx_g_context != nullptr) {
    // Release the callback slots while the context is still alive.
    kwx_host_release_callbacks(kwx_g_context);
    JS_FreeContext(kwx_g_context);
    kwx_g_context = nullptr;
  }

  if (kwx_g_runtime != nullptr) {
    JS_FreeRuntime(kwx_g_runtime);
    kwx_g_runtime = nullptr;
  }
}

JSContext *kwx_runtime_context() { return kwx_g_context; }

JSRuntime *kwx_runtime_jsruntime() { return kwx_g_runtime; }

void kwx_host_drain_jobs() {
  if (kwx_g_runtime == nullptr) {
    return;
  }

  JSContext *job_context = nullptr;
  int status = 0;
  do {
    status = JS_ExecutePendingJob(kwx_g_runtime, &job_context);
  } while (status > 0);

  if (status < 0 && job_context != nullptr) {
    kwx_report_exception(job_context);
  }
}

bool kwx_runtime_eval_file(const std::string &path, int &exit_code) {
  KwxTraceMark("run-main-begin");

  exit_code = 0;

  if (kwx_g_context == nullptr) {
    std::fprintf(stderr, "[kwx_ts] Runtime is not initialized\n");
    exit_code = 1;
    return false;
  }

  // The Deno shim owns module loading: hand the entry path to __kwx_run_main(),
  // which resolves and evaluates it through the CommonJS-style loader.
  JSValue global_object = JS_GetGlobalObject(kwx_g_context);
  JSValue run_main =
      JS_GetPropertyStr(kwx_g_context, global_object, "__kwx_run_main");
  JS_FreeValue(kwx_g_context, global_object);

  if (!JS_IsFunction(kwx_g_context, run_main)) {
    JS_FreeValue(kwx_g_context, run_main);
    std::fprintf(stderr, "[kwx_ts] __kwx_run_main is unavailable\n");
    exit_code = 1;
    return false;
  }

  JSValue path_value = JS_NewString(kwx_g_context, path.c_str());
  JSValue result =
      JS_Call(kwx_g_context, run_main, JS_UNDEFINED, 1, &path_value);
  KwxTraceMark("run-main-end");
  JS_FreeValue(kwx_g_context, path_value);
  JS_FreeValue(kwx_g_context, run_main);

  const bool eval_ok = !JS_IsException(result);
  JS_FreeValue(kwx_g_context, result);

  if (!eval_ok) {
    if (kwx_host_consume_exit_exception(kwx_g_context)) {
      exit_code = kwx_g_exit_code;
      kwx_host_drain_jobs();
      return true;
    }
    kwx_report_exception(kwx_g_context);
    exit_code = 1;
    return false;
  }

  kwx_host_drain_jobs();
  exit_code = kwx_g_exit_requested ? kwx_g_exit_code : 0;
  return true;
}

void kwx_runtime_set_args(const std::vector<std::string> &args) {
  kwx_g_args = args;
}

const std::vector<std::string> &kwx_runtime_arguments() { return kwx_g_args; }

void kwx_runtime_set_exit_code(int code) {
  kwx_g_exit_code = code;
  kwx_g_exit_requested = true;
}

int kwx_runtime_exit_code() { return kwx_g_exit_code; }

bool kwx_host_consume_exit_exception(JSContext *ctx) {
  JSValue exception = JS_GetException(ctx);
  bool is_exit = false;
  if (JS_IsObject(exception)) {
    JSValue flag = JS_GetPropertyStr(ctx, exception, "__kwx_exit");
    if (JS_ToBool(ctx, flag) > 0) {
      is_exit = true;
      JSValue code = JS_GetPropertyStr(ctx, exception, "code");
      std::int32_t value = 0;
      std::ignore = JS_ToInt32(ctx, &value, code);
      JS_FreeValue(ctx, code);
      kwx_runtime_set_exit_code(value);
    }
    JS_FreeValue(ctx, flag);
  }

  if (!is_exit) {
    // Not the exit sentinel: restore the exception so the caller can report it.
    JS_Throw(ctx, exception);
    return false;
  }

  JS_FreeValue(ctx, exception);
  return true;
}

void kwx_host_release_callbacks(JSContext *ctx) {
  kwx_runtime_release_callbacks(ctx);
}

void kwx_host_report_exception(JSContext *ctx) {
  if (ctx != nullptr) {
    kwx_report_exception(ctx);
  }
}
